/**
 * Очистка хеша от всего, что не является маршрутом.
 *
 * У приложения маршрутизатор на хеше: `#/`, `#/trip/<id>` и так далее.
 * Любой другой хеш он считает несуществующим маршрутом и показывает
 * пустой экран — проверено в браузере: `#ref=vk_chat` даёт белую
 * страницу вместо приложения.
 *
 * А хеш туда попадает легко и не по нашей воле:
 *
 * — рекламная ссылка с меткой источника: `vk.ru/app54794463#chat` —
 *   именно так считают переходы из разных мест;
 * — Telegram, когда прислал только `#tgWebAppStartParam=…`, без
 *   initData: перехват параметров запуска такой хеш не узнаёт.
 *
 * Цена ошибки несимметрична: метку мы всё равно нигде не читаем, а
 * пустой экран теряет человека, который уже нажал на ссылку. Поэтому
 * непонятный хеш просто отбрасывается.
 *
 * Вызывать до создания маршрутизатора и после перехвата параметров
 * Telegram: тот забирает свой хеш сам.
 */
export function stripLaunchHash(): void {
  if (typeof window === 'undefined') {
    return;
  }

  const hash = window.location.hash;
  if (hash === '' || hash === '#' || hash.startsWith('#/')) {
    return;
  }

  window.history.replaceState(
    null,
    '',
    `${window.location.pathname}${window.location.search}#/`,
  );
}

-- Откат миграции 20261013100000_hub_routes.
--
-- Prisma down-миграций не умеет, поэтому файл лежит рядом и запускается
-- руками:
--   psql "$DATABASE_URL" -f apps/api/prisma/migrations/20261013100000_hub_routes/rollback.sql
--
-- Порядок обратный: сначала вернуть данные, потом убрать колонку —
-- иначе отметка, по которой их узнают, исчезнет вместе с ней.
--
-- Откат ПОЛНЫЙ только пока эти строки никто не трогал. Если автор после
-- миграции сам завершил или снова отменил своё объявление, запрос ниже
-- его не вернёт: условие требует CANCELLED с нашей отметкой.
--
-- И главное: откат кода без отката данных безопасен — объявление по
-- исчезнувшему направлению просто останется отменённым. Поэтому этот
-- файл нужен только если справочник вернули назад по-настоящему.

-- 1. Вернуть в ACTIVE ровно то, что закрыла миграция.
UPDATE "trips"
   SET "status" = 'ACTIVE',
       "cancelReason" = NULL
 WHERE "status" = 'CANCELLED'
   AND "cancelReason" = 'ROUTE_REMOVED';


-- Радиальный справочник направлений: Оренбург — хаб, остальные пункты — спицы.
--
-- Схему меняет одна строка — колонка "cancelReason". Остальное — разовая
-- уборка данных: пара Акбулак↔Соль-Илецк перестала быть направлением,
-- и её активные объявления нельзя оставить как есть. Активное
-- объявление — это обещание: кто-то позвонит и приедет на место сбора.
-- Поездки по нему больше не предусмотрено, значит обещание надо снять.
--
-- ВАЖНО: перед применением выгрузите задетые строки, иначе после UPDATE
-- будет не с кем связаться:
--   npm run export:removed-routes -w @vk-rideshare/api > removed-routes.csv
--
-- Откат — rollback.sql в этой же папке. Prisma его не запускает: это
-- ручная операция, и выполняется она так же вручную, через psql.

-- 1. Отметка причины. Необязательная, без значения по умолчанию: у всех
--    существующих строк причины нет и быть не должно.
ALTER TABLE "trips" ADD COLUMN "cancelReason" TEXT;

-- 2. Активные объявления по исчезнувшим направлениям — в CANCELLED.
--
--    Условие повторяет правило справочника, а не перечисляет удалённые
--    пары: уцелеть должно объявление, у которого ровно один конец —
--    Оренбург, а другой — спица. Так UPDATE закроет и пару
--    Акбулак↔Соль-Илецк, и любой мусор, попавший в базу до того, как
--    маршруты начали проверяться на входе.
--
--    Трогаются только ACTIVE. COMPLETED и CANCELLED — это история: по
--    ним уже съездили или их уже закрыли, и переписывать её нечестно.
UPDATE "trips"
   SET "status" = 'CANCELLED',
       "cancelReason" = 'ROUTE_REMOVED'
 WHERE "status" = 'ACTIVE'
   AND NOT (
         (
           "fromCity" = 'Оренбург'
           AND "toCity" IN ('Соль-Илецк', 'Акбулак', 'Илек', 'Александровка')
         )
      OR (
           "toCity" = 'Оренбург'
           AND "fromCity" IN ('Соль-Илецк', 'Акбулак', 'Илек', 'Александровка')
         )
       );

